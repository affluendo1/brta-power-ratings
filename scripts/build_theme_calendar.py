"""Generate the Theme Calendar catalogue from Monkeytype's TypeScript theme constants."""
import json
import re
import sys
from pathlib import Path

FIELDS = ("bg", "main", "sub", "subAlt", "text", "error", "colorfulError")


def build(source):
    palettes = []
    for key, body in re.findall(r'^  ("[^"]+"|\w+): \{(.*?)^  \},', source, re.M | re.S):
        colors = dict(re.findall(r'^    (\w+): "(#[0-9a-fA-F]+)",', body, re.M))
        identifier = key.strip('"')
        palettes.append({
            "id": identifier,
            "name": identifier.replace("_", " ").replace("-", " ").title(),
            "source": identifier,
            "colors": [colors[field] for field in FIELDS],
        })
    if not palettes or len(palettes) > 366:
        raise ValueError("Expected between 1 and 366 upstream presets")
    variants = 366 - len(palettes)
    titles = ("Afterglow", "Blue Hour", "First Light", "Midnight Edition", "Second Light")
    catalogue = []
    for index, original in enumerate(palettes):
        catalogue.append(original)
        for variant_index in range(index, variants, len(palettes)):
            paired = palettes[(variant_index + 41) % len(palettes)]
            colors = list(original["colors"])
            colors[1] = paired["colors"][1]
            colors[6] = paired["colors"][6]
            catalogue.append({
                "id": f'edition-{variant_index + 1}',
                "name": original["name"] + " · " + titles[variant_index % len(titles)],
                "colors": colors,
            })
    return catalogue


if __name__ == "__main__":
    themes = build(Path(sys.argv[1]).read_text())
    output = Path("web/themes/theme-calendar/presets.js")
    output.write_text(
        "// Generated by scripts/build_theme_calendar.py. See SOURCE.md for attribution.\n"
        "window.BRTAThemeCalendarPresets = [\n"
        + ",\n".join("  " + json.dumps(theme, ensure_ascii=False, separators=(",", ":")) for theme in themes)
        + "\n];\n"
    )
